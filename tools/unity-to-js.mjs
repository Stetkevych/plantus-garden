// unity-to-js.mjs — turn the Unity prototype's C# plant data into an ES module
// the Lab page can import, so the C# stays the single source of truth.
//
//   node tools/unity-to-js.mjs        -> writes lab/plants.js
//
// Reads unity/plantDatabase.cs (the roster) and unity/PlantUnlockSystem.cs
// (starter ids, tier level gates and costs).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const db = readFileSync(join(ROOT, 'unity/plantDatabase.cs'), 'utf8');
const unlock = readFileSync(join(ROOT, 'unity/PlantUnlockSystem.cs'), 'utf8');

/** Body of the `Name = new X { ... }` block, matched by brace depth. */
function block(src, name) {
  const at = src.search(new RegExp(`\\b${name}\\s*=\\s*new\\s+\\w+\\s*\\{`));
  if (at < 0) return '';
  let i = src.indexOf('{', at), depth = 0;
  const start = i;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(start + 1, i);
  }
  return '';
}

const lc = (s) => s[0].toLowerCase() + s.slice(1);
function fields(body) {
  const out = {};
  for (const [, k, v] of body.matchAll(/(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"/g)) out[lc(k)] = v;
  for (const [, k, v] of body.matchAll(/(\w+)\s*=\s*(-?\d+)\b/g)) out[lc(k)] = Number(v);
  for (const [, k, v] of body.matchAll(/(\w+)\s*=\s*\w+\.(\w+)/g)) out[lc(k)] = v;
  return out;
}

// Each entry starts with:  "id",\n  new PlantData
const starts = [...db.matchAll(/"([a-z0-9_]+)",\s*new PlantData\s*\{/g)];
const plants = starts.map((m, n) => {
  const end = n + 1 < starts.length ? starts[n + 1].index : db.length;
  const src = db.slice(m.index, end);
  const top = src.replace(/\b(Aesthetic|PowerVisual|Stats)\s*=\s*new\s+\w+\s*\{[^}]*\}/g, '');
  const head = fields(top);
  const traits = (/Traits\s*=\s*new List<string>\s*\{([^}]*)\}/.exec(src)?.[1] || '')
    .split(',').map((s) => s.trim().replace(/^"|"$/g, '')).filter(Boolean);
  return {
    id: m[1],
    name: head.displayName,
    latin: head.speciesName,
    tier: head.unlockTier,
    element: head.element,
    aesthetic: fields(block(src, 'Aesthetic')),
    power: fields(block(src, 'PowerVisual')),
    stats: fields(block(src, 'Stats')),
    traits,
  };
});

const starterIds = [...(/StarterPlantIds[^{]*\{([^}]*)\}/.exec(unlock)?.[1] || '').matchAll(/"([a-z0-9_]+)"/g)].map((x) => x[1]);
const table = (name) => Object.fromEntries(
  [...(new RegExp(`${name}[^{]*\\{([\\s\\S]*?)\\};`).exec(unlock)?.[1] || '').matchAll(/UnlockTier\.(\w+),\s*(\d+)/g)]
    .map(([, t, v]) => [t, Number(v)]));

const tierLevel = table('TierLevelRequirements');
const tierCost = table('TierCurrencyCosts');

// Fail loudly rather than ship a half-parsed roster.
const bad = plants.filter((p) => !p.name || !p.tier || !p.element || !p.stats.health || !p.power.attackName);
if (bad.length || !plants.length || !starterIds.length || Object.keys(tierLevel).length !== 6) {
  console.error('Parse problem:', { plants: plants.length, bad: bad.map((b) => b.id), starterIds, tierLevel, tierCost });
  process.exit(1);
}

const out = `// GENERATED by tools/unity-to-js.mjs from unity/*.cs. Do not edit by hand.

export const PLANTS = ${JSON.stringify(plants, null, 2)};

export const STARTER_IDS = ${JSON.stringify(starterIds)};
export const TIER_LEVEL = ${JSON.stringify(tierLevel)};
export const TIER_COST = ${JSON.stringify(tierCost)};
export const TIERS = ${JSON.stringify(Object.keys(tierLevel))};
`;
writeFileSync(join(ROOT, 'lab/plants.js'), out);
console.log(`lab/plants.js: ${plants.length} plants, starters ${starterIds.join(', ')}`);
